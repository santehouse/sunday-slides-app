type FieldOverrides = Partial<TemplateFieldSeed> & Pick<TemplateFieldSeed, "fieldKey" | "x" | "y" | "width" | "height">;

/** Letter-spacing in Canva is in em; the engine wants px at 1920 scale. */
function em(size: number, value: number): number {
  return Math.round(size * value * 100) / 100;
}

let order = 0;

function field(overrides: FieldOverrides): TemplateFieldSeed {
  order += 1;
  const fontSize = overrides.fontSize ?? 56;
  return {
    labelEn: overrides.fieldKey,
    labelFr: overrides.fieldKey,
    teamEditable: true,
    required: false,
    fontFamily: BRAND_SANS,
    fontSize,
    minFontSize: Math.round(fontSize * 0.7),
    fontWeight: 400,
    fontStyle: "normal",
    lineHeight: 1.1,
    letterSpacing: 0,
    alignment: "left",
    textColor: BRAND_COLORS.white,
    maxLines: 2,
    overflowMode: "auto_fit",
    textTransform: "none",
    sortOrder: order,
    ...overrides,
  };
}

/** Big display-serif title: tight tracking, tight leading — the signature of every panel. */
function serif(overrides: FieldOverrides): TemplateFieldSeed {
  const fontSize = overrides.fontSize ?? 260;
  return field({
    fontFamily: BRAND_SERIF,
    fontSize,
    minFontSize: Math.round(fontSize * 0.6),
    lineHeight: 0.8,
    letterSpacing: em(fontSize, -0.06),
    ...overrides,
  });
}

/** Locked decorative text — always renders `defaultValue`, never offered to the Sunday team. */
function locked(overrides: FieldOverrides & { defaultValue: string }): TemplateFieldSeed {
  // Decorative one-liners: the preferred size is the design, the box height is only a hint.
  return field({ teamEditable: false, required: false, overflowMode: "flex_height", ...overrides });
}

/**
 * Locked display title. Kept on `auto_fit`: Times New Roman sets wider than the condensed
 * display face in the Canva masters, so a title may need to step down a little to stay
 * inside its box instead of overflowing.
 */
function lockedSerif(overrides: FieldOverrides & { defaultValue: string }): TemplateFieldSeed {
  return serif({ teamEditable: false, required: false, ...overrides });
}

